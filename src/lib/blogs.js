export function getAllBlogs() {
  return blogTopics
    .map((blog, idx) => {
      const month = String(8 - Math.floor(idx / 3)).padStart(2, "0");
      const day = String(28 - (idx % 20)).padStart(2, "0");
      return {
        ...blog,
        author: "AIShyp Logistics Squad",
        publishedDate: `2026-${month}-${day}`,
        featuredImage: TOPIC_IMAGE_MAP[blog.slug] || FALLBACK_BLOG_IMAGE,
        tags: [
          blog.keyword,
          "Shipping Aggregator OS",
          "Logistics Automation",
        ],
      };
    })
    .sort((a, b) => new Date(b.publishedDate).getTime() - new Date(a.publishedDate).getTime());
}

export function getBlogBySlug(slug) {
  return getAllBlogs().find((blog) => blog.slug === slug);
}

export function getRelatedBlogs(slug, limit = 2) {
  const allBlogs = getAllBlogs();
  const current = allBlogs.find((blog) => blog.slug === slug);
  if (!current) return allBlogs.slice(0, limit);

  return allBlogs.filter((b) => b.slug !== slug).slice(0, limit);
}
